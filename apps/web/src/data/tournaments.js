/**
 * The tournaments catalogue.
 *
 * Static, like `PROMOTIONS` and `HOME_BANNERS` in `catalog.js`, and for the
 * same reason: there is no tournaments endpoint yet. `docs/10` puts them in the
 * `bonus` service alongside Promotions and VIP, so this file is the shape that
 * adapter will fill, not a shape invented for the view. Every field below is
 * one the reference's own card renders.
 *
 * `endsInHours` rather than a date is the one deliberate difference. A literal
 * `endsAt` would be correct for exactly as long as it took to go stale, and a
 * page whose headline feature is a live countdown cannot ship with three timers
 * frozen at zero. The offset is resolved against load time in `TOURNAMENTS`
 * below, so the clocks always have something to count. A real integration
 * replaces the whole computation with the server's own timestamp — which is
 * why the exported field is already `endsAt`, and nothing downstream knows the
 * offset existed.
 *
 * @typedef {object} Tournament
 * @property {string} slug     URL segment: `/tournaments/<slug>`
 * @property {string} title    Shown on the card, e.g. "Gold Challenge #2"
 * @property {'gold'|'silver'|'bronze'} tier   Drives the generated artwork
 * @property {'active'|'finished'} status
 * @property {string} prizePool  Pre-formatted, because the reference's own
 *                               values are not all currency ("10,000 USDT +
 *                               Free Spins")
 * @property {string} leader     Masked alias of whoever is first, as the
 *                               reference masks it: `y*****f`
 * @property {string} art        Generated by `scripts/generate-assets.mjs`
 * @property {string} endsAt     ISO timestamp the countdown runs to
 */

